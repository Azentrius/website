// Builds two files from the design system's tokens.css (vendor/design-system/):
// - src/styles/tokens.css: the tokens without their @font-face rules. Those point at a fonts/ folder
//   next to the stylesheet; this site serves the four fonts it uses from /fonts/ (see site.css).
// - src/styles/theme.css: "Azentrius hell" by default, "Azentrius dunkel" when the device prefers dark,
//   as the design system asks for project pages.
// Run after updating the vendored files: npm run design
import { readFileSync, writeFileSync } from "node:fs";

const tokens = readFileSync(new URL("../vendor/design-system/tokens.css", import.meta.url), "utf8");

function block(theme) {
  const match = tokens.match(new RegExp(`\\[data-theme="${theme}"\\]\\s*\\{([^}]*)\\}`));
  if (!match) throw new Error(`tokens.css has no block for ${theme}`);
  return match[1].trim().split("\n").map((line) => `  ${line.trim()}`).join("\n");
}

const withoutFonts = tokens
  .split("\n")
  .filter((line) => !line.startsWith("@font-face"))
  .join("\n");
if (withoutFonts.includes("@font-face")) throw new Error("tokens.css has an @font-face rule over several lines");
writeFileSync(
  new URL("../src/styles/tokens.css", import.meta.url),
  `/* Generated by scripts/design.mjs from vendor/design-system/tokens.css, without @font-face. Do not edit. */\n${withoutFonts}`,
);
console.log("src/styles/tokens.css written");

const css = `/* Generated by scripts/design.mjs from vendor/design-system/tokens.css. Do not edit. */
:root[data-theme="azentrius"] {
  color-scheme: light;
${block("azentrius-hell")}
}
@media (prefers-color-scheme: dark) {
  :root[data-theme="azentrius"] {
    color-scheme: dark;
${block("azentrius-dunkel").replaceAll("\n  ", "\n    ").replace(/^ {2}/, "    ")}
  }
}
`;
writeFileSync(new URL("../src/styles/theme.css", import.meta.url), css);
console.log("src/styles/theme.css written");
